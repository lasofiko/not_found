def correlation(values, lag):
    y = np.asarray(values, dtype=float)
    if len(y) <= lag + 1 or np.std(y[lag:]) == 0 or np.std(y[:-lag]) == 0:
        return None
    return float(np.corrcoef(y[lag:], y[:-lag])[0, 1])


def analyze(history):
    groups = defaultdict(list)
    for row in history:
        groups[row["series_id"]].append(row)
    profiles = []
    for series_id, rows in sorted(groups.items()):
        y = np.array([float(r["value"]) for r in rows])
        month_means = {
            str(month): float(np.mean([float(r["value"]) for r in rows if int(r["period"][5:]) == month]))
            for month in range(1, 13)
        }
        profiles.append(
            {
                "series_id": series_id,
                "region": rows[0]["region"],
                "port": rows[0]["port"],
                "cargo_group": rows[0]["cargo_group"],
                "n": len(y),
                "first_period": rows[0]["period"],
                "last_period": rows[-1]["period"],
                "mean": float(y.mean()),
                "median": float(np.median(y)),
                "variance": float(y.var(ddof=1)),
                "min": float(y.min()),
                "max": float(y.max()),
                "cv": float(y.std(ddof=1) / y.mean()),
                "acf1": correlation(y, 1),
                "acf12": correlation(y, 12),
                "month_means_descriptive": month_means,
                "seasonality_conclusion": (
                    "3–4 наблюдения на месяц; ACF не доказывает устойчивую сезонность, тренд смешан с сезонностью"
                ),
                "status": "estimated",
                "unit": "tonnes",
                "frequency": "month",
                "direction": None,
                "source_ids": sorted({r[k] for r in rows for k in ("source_id", "previous_source_id") if r[k]}),
            }
        )
    return profiles


